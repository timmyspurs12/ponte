import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import sha3 from "js-sha3";

import {
  ABI_HASH_ALGORITHM,
  EXPECTED_BUILD_CONFIGURATION,
  REGISTRY_ABI_VERSION,
  REGISTRY_CONTRACT_NAME,
  REGISTRY_CONTRACT_VERSION,
  RUNTIME_BYTECODE_HASH_ALGORITHM,
} from "./registry-deployment-constants.mjs";

const { keccak256 } = sha3;

export const DEFAULT_REGISTRY_ARTIFACT_PATH =
  "out/PonteRouteDecisionEvidenceRegistry.sol/PonteRouteDecisionEvidenceRegistry.json";

export class RegistryBuildIdentityError extends Error {
  constructor(code) {
    super(code);
    this.name = "RegistryBuildIdentityError";
    this.code = code;
  }
}

function fail(code) {
  throw new RegistryBuildIdentityError(code);
}

function isHex(value) {
  return typeof value === "string" && /^0x[0-9a-fA-F]*$/.test(value);
}

function bytesFromHex(value, code) {
  if (!isHex(value) || value.length === 2 || value.length % 2 !== 0) fail(code);
  return Buffer.from(value.slice(2), "hex");
}

/** Stable JSON serialization for the ABI hash recorded in a manifest. */
export function canonicalJson(value) {
  if (value === null) return "null";
  if (typeof value === "string" || typeof value === "boolean")
    return JSON.stringify(value);
  if (typeof value === "number") {
    if (!Number.isFinite(value)) fail("CANONICAL_JSON_INVALID_NUMBER");
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (typeof value === "object") {
    const entries = Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`);
    return `{${entries.join(",")}}`;
  }
  fail("CANONICAL_JSON_UNSUPPORTED_VALUE");
}

export function sha256Hex(value) {
  return `0x${createHash("sha256").update(value).digest("hex")}`;
}

export function keccak256Hex(bytes) {
  return `0x${keccak256(bytes)}`;
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    fail("REGISTRY_ARTIFACT_UNREADABLE");
  }
}

/**
 * Extracts the reproducible V1 identity from the local Foundry artifact.
 * This command is offline: it reads only the artifact generated by `npm run build`.
 */
export function readRegistryBuildIdentity(
  artifactPath = DEFAULT_REGISTRY_ARTIFACT_PATH,
) {
  const artifact = readJson(artifactPath);
  const metadata = artifact?.metadata;
  const runtimeBytecode = artifact?.deployedBytecode?.object;
  const creationBytecode = artifact?.bytecode?.object;
  const abi = artifact?.abi;

  if (!metadata || typeof metadata !== "object")
    fail("REGISTRY_ARTIFACT_METADATA_INVALID");
  if (!Array.isArray(abi)) fail("REGISTRY_ARTIFACT_ABI_INVALID");

  const compiler = metadata?.compiler?.version;
  const optimizer = metadata?.settings?.optimizer;
  const evmVersion = metadata?.settings?.evmVersion;
  // solc omits viaIR from metadata when it is false; absence therefore means false.
  const viaIR = metadata?.settings?.viaIR === true;
  if (
    compiler !== EXPECTED_BUILD_CONFIGURATION.solidityCompiler ||
    optimizer?.enabled !== EXPECTED_BUILD_CONFIGURATION.optimizer.enabled ||
    optimizer?.runs !== EXPECTED_BUILD_CONFIGURATION.optimizer.runs ||
    evmVersion !== EXPECTED_BUILD_CONFIGURATION.evmVersion ||
    viaIR !== EXPECTED_BUILD_CONFIGURATION.viaIR
  ) {
    fail("REGISTRY_ARTIFACT_BUILD_CONFIGURATION_MISMATCH");
  }

  return Object.freeze({
    buildIdentityVersion: 1,
    contract: Object.freeze({
      name: REGISTRY_CONTRACT_NAME,
      version: REGISTRY_CONTRACT_VERSION,
    }),
    compiler: compiler,
    optimizer: Object.freeze({
      enabled: optimizer.enabled,
      runs: optimizer.runs,
    }),
    evmVersion,
    viaIR,
    creationBytecodeHashAlgorithm: RUNTIME_BYTECODE_HASH_ALGORITHM,
    creationBytecodeHash: keccak256Hex(
      bytesFromHex(creationBytecode, "REGISTRY_CREATION_BYTECODE_INVALID"),
    ),
    runtimeBytecodeHashAlgorithm: RUNTIME_BYTECODE_HASH_ALGORITHM,
    runtimeBytecodeHash: keccak256Hex(
      bytesFromHex(runtimeBytecode, "REGISTRY_RUNTIME_BYTECODE_INVALID"),
    ),
    runtimeBytecodeBytes: (runtimeBytecode.length - 2) / 2,
    abi: Object.freeze({
      version: REGISTRY_ABI_VERSION,
      hashAlgorithm: ABI_HASH_ALGORITHM,
      hash: sha256Hex(canonicalJson(abi)),
    }),
  });
}

function parseArgs(argv) {
  if (argv.length === 0) return DEFAULT_REGISTRY_ARTIFACT_PATH;
  if (argv.length === 2 && argv[0] === "--artifact") return argv[1];
  throw new RegistryBuildIdentityError("USAGE: --artifact <path>");
}

function main() {
  const artifactPath = parseArgs(process.argv.slice(2));
  const identity = readRegistryBuildIdentity(
    resolve(process.cwd(), artifactPath),
  );
  process.stdout.write(`${JSON.stringify(identity, null, 2)}\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
